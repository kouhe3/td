"""Compare SessionConnection's packet policy with TDLib, byte for byte.

Both probes read the same script and print one line per op plus callback
events. The script is generated here (message ids must be close to wall-clock
time, like a real session); the corpus itself is fixed.

Usage:
    uv run python tools/session_diff.py
    uv run python tools/session_diff.py --selftest

Exit codes: 0 = PASS, 1 = mismatch, 2 = missing binary.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import struct
import subprocess
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
MSYS_BIN = "C:/msys64/ucrt64/bin"
DEFAULT_CPP = "C:/tmp/td-probe/session_probe.exe"
DEFAULT_RS = REPO / "rust/target/x86_64-pc-windows-gnu/release/session_probe.exe"

BAD_MSG_CODES = [16, 17, 18, 19, 20, 32, 33, 34, 35, 64, 99]


def i32(value: int) -> bytes:
    return struct.pack("<I", value & 0xFFFFFFFF)


def i64(value: int) -> bytes:
    return struct.pack("<Q", value & 0xFFFFFFFFFFFFFFFF)


def tl_string(text: str) -> bytes:
    data = text.encode()
    pad = (4 - (1 + len(data)) % 4) % 4
    return bytes([len(data)]) + data + b"\0" * pad


def rpc_ok(req: int, obj: int = 0x12345678) -> bytes:
    return i32(0xF35C6D01) + i64(req) + i32(obj)


def rpc_error(req: int, code: int, message: str) -> bytes:
    return i32(0xF35C6D01) + i64(req) + i32(0x2144CA19) + i32(code) + tl_string(message)


def bad_msg_notification(bad_msg_id: int, seq: int, code: int) -> bytes:
    return i32(0xA7EFF811) + i64(bad_msg_id) + i32(seq) + i32(code)


def bad_server_salt(bad_msg_id: int, seq: int, code: int, salt: int) -> bytes:
    return i32(0xEDAB447B) + i64(bad_msg_id) + i32(seq) + i32(code) + i64(salt)


def msgs_ack(message_ids: list[int]) -> bytes:
    return i32(0x62D6B459) + i32(0x1CB5C415) + i32(len(message_ids)) + b"".join(i64(mid) for mid in message_ids)


def new_session_created(first_message_id: int, unique_id: int, salt: int) -> bytes:
    return i32(0x9EC20908) + i64(first_message_id) + i64(unique_id) + i64(salt)


def tl_bytes(data: bytes) -> bytes:
    pad = (4 - (1 + len(data)) % 4) % 4
    return bytes([len(data)]) + data + b"\0" * pad


def msg_detailed_info(msg_id: int, answer_msg_id: int, size: int, status: int) -> bytes:
    return i32(0x276D3EC6) + i64(msg_id) + i64(answer_msg_id) + i32(size) + i32(status)


def msg_new_detailed_info(answer_msg_id: int, size: int, status: int) -> bytes:
    return i32(0x809DB6DF) + i64(answer_msg_id) + i32(size) + i32(status)


def msgs_all_info(message_ids: list[int], info: bytes) -> bytes:
    return i32(0x8CC0D131) + i32(0x1CB5C415) + i32(len(message_ids)) + b"".join(i64(mid) for mid in message_ids) + tl_bytes(info)


def msgs_state_info(req_msg_id: int, info: bytes) -> bytes:
    return i32(0x04DEB57D) + i64(req_msg_id) + tl_bytes(info)


def envelope(message_id: int, seq: int, body: bytes) -> bytes:
    return i64(message_id) + i32(seq) + i32(len(body)) + body


def container(children: list[bytes]) -> bytes:
    return i32(0x73F1F8DC) + i32(len(children)) + b"".join(children)


def build_script(now: int, first_code: int = 16) -> str:
    def mid(low: int) -> int:
        return (now << 32) | low

    lines = ["# generated by tools/session_diff.py", "newconn 777 1234"]
    # rpc_result: default object and rpc_error
    lines.append(f"in {mid(1)} 1 {rpc_ok(4001).hex()}")
    lines.append("salt")
    lines.append(f"in {mid(3)} 1 {rpc_error(4002, 400, 'PHONE_NUMBER_INVALID').hex()}")
    # container: one result and one notification
    lines.append("newconn 777 1234")
    lines.append(
        f"in {mid(5)} 1 {container([envelope(4002, 1, rpc_ok(4001)), envelope(4004, 1, bad_msg_notification(4003, 1, 16))]).hex()}"
    )
    # bad_server_salt: the salt really changes
    lines.append("newconn 777 1234")
    lines.append(f"in {mid(7)} 1 {bad_server_salt(4001, 1, 48, 0x99AABBCCDDEEFF00).hex()}")
    lines.append("salt")
    # every error_code branch on a fresh connection
    for index, code in enumerate(BAD_MSG_CODES):
        if index == 0:
            code = first_code
        lines.append("newconn 777 1234")
        lines.append(f"in {mid(11 + 2 * index)} 1 {bad_msg_notification(4001, 1, code).hex()}")
    # unknown constructor: the update path, then the same id again (duplicate)
    lines.append("newconn 777 1234")
    lines.append(f"in {mid(41)} 1 {i32(0x12345678).hex()}")
    lines.append(f"in {mid(41)} 1 {i32(0x12345678).hex()}")
    # msgs_ack: one ack callback per id
    lines.append("newconn 777 1234")
    lines.append(f"in {mid(43)} 1 {msgs_ack([4001, 4002]).hex()}")
    # new_session_created: unique_id and first_message_id reach the callback
    lines.append("newconn 777 1234")
    lines.append(f"in {mid(45)} 1 {new_session_created(4001, 0x1122334455667788, 0x99AABBCCDDEEFF00).hex()}")
    # rpc_result with req_msg_id == 0 is rejected and closes the session
    lines.append("newconn 777 1234")
    lines.append(f"in {mid(47)} 1 {rpc_ok(0).hex()}")
    # detailed-info family and per-message states
    lines.append("newconn 777 1234")
    lines.append(f"in {mid(49)} 1 {msg_detailed_info(4001, 4002, 30, 40).hex()}")
    lines.append(f"in {mid(51)} 1 {msg_new_detailed_info(4003, 31, 41).hex()}")
    lines.append("newconn 777 1234")
    lines.append(f"in {mid(53)} 1 {msgs_all_info([4001, 4002], bytes([1, 5])).hex()}")
    # no service query is registered, so msgs_state_info is an error
    lines.append("newconn 777 1234")
    lines.append(f"in {mid(55)} 1 {msgs_state_info(4001, bytes([1])).hex()}")
    return "\n".join(lines) + "\n"


def run(binary: str, script_path: Path, env: dict[str, str]) -> tuple[int, str]:
    proc = subprocess.run([binary, str(script_path)], capture_output=True, env=env)
    # printf on Windows translates \n to \r\n; Rust writes bytes as-is.
    return proc.returncode, proc.stdout.decode("utf-8", "replace").replace("\r\n", "\n")


def corpus_digest(script: str) -> str:
    """Message ids carry the wall clock; hash the shape, not the timestamps."""
    template = "\n".join(re.sub(r"^in \d+", "in", line) for line in script.splitlines())
    return hashlib.md5(template.encode()).hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cpp", default=DEFAULT_CPP)
    parser.add_argument("--rs", default=str(DEFAULT_RS))
    parser.add_argument("--selftest", action="store_true")
    args = parser.parse_args()

    for path in (args.cpp, args.rs):
        if not Path(path).exists():
            print(f"MISSING {path}")
            return 2

    now = int(time.time())
    script = build_script(now)
    print(f"corpus md5={corpus_digest(script)} ops={len(script.splitlines())}")

    script_path = REPO / "work" / "session_script.txt"
    script_path.parent.mkdir(exist_ok=True)
    script_path.write_bytes(script.encode("utf-8"))

    env = dict(os.environ)
    env["PATH"] = MSYS_BIN + ";" + env.get("PATH", "")

    cpp_rc, cpp_out = run(args.cpp, script_path, env)
    rs_rc, rs_out = run(args.rs, script_path, env)
    if cpp_rc != 0 or rs_rc != 0:
        print(f"FAIL exit codes oracle={cpp_rc} rust={rs_rc}")
        return 1
    if cpp_out != rs_out:
        cpp_lines = cpp_out.splitlines()
        rs_lines = rs_out.splitlines()
        for index, (left, right) in enumerate(zip(cpp_lines, rs_lines)):
            if left != right:
                print(f"DIFF line {index + 1}: oracle={left!r} rust={right!r}")
                return 1
        print(f"DIFF line count: oracle={len(cpp_lines)} rust={len(rs_lines)}")
        return 1

    # A/A floor: same script twice, independent processes.
    _, again = run(args.cpp, script_path, env)
    if again != cpp_out:
        print("FLOOR FAIL: the oracle is not deterministic")
        return 1

    if args.selftest:
        # One changed error code must change the events.
        mutated = build_script(now, first_code=17)
        script_path.write_bytes(mutated.encode("utf-8"))
        _, mutated_out = run(args.cpp, script_path, env)
        if mutated_out == cpp_out:
            print("SELFTEST FAIL: a code change did not change the events")
            return 1
        print("SELFTEST OK: comparator sees an error_code change")

    print(f"PASS lines={len(cpp_out.splitlines())}")
    script_path.unlink(missing_ok=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())