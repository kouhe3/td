"""Extract the MIME tables from TDLib's generated gperf sources into Rust.

命令:
    python tools/gen_mime_tables.py            # 重新生成 rust/src/mime_tables.rs
    python tools/gen_mime_tables.py --check    # 重新生成并逐字节比对，不一致退出 1

判据:
    两个 gperf 表各按 key 排序写入；`--check` 必须与仓库里已提交的 rust/src/mime_tables.rs 逐字节相同。
    行为判据在 tools/tdjson_diff.py（getFileMimeType / getFileExtension 的 cell）。

覆盖边界:
    只覆盖 gperf 的 `%ignore-case` 关键字查找（TDLib MimeType.cpp 的 from_extension / to_extension）。
    覆盖不到：未知扩展名/未知 MIME 的日志副作用（C++ 会 LOG(INFO)），以及非 ASCII 关键字（表中不存在）。

失效条件:
    TDLib 改了 `tdutils/generate/mime_types.txt`，或 `generate_mime_types_gperf` 的拆分规则变化。
    此时先重新构建 C++（生成 auto/*.gperf），再跑本脚本，并重判 gate。
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AUTO = ROOT / "tdutils" / "generate" / "auto"
FIXTURES = ROOT / "tools" / "fixtures"
OUT = ROOT / "rust" / "src" / "mime_tables.rs"
PAIR = re.compile(r'^"([^"]*)",\s*"([^"]*)"\s*$')

SOURCES = [
    ("EXTENSION_TO_MIME", "extension_to_mime_type.gperf", "extension", "mime_type"),
    ("MIME_TO_EXTENSION", "mime_type_to_extension.gperf", "mime_type", "extension"),
]


def source_path(name: str) -> Path:
    # 仓库自带的 fixture 优先：gperf 是构建产物（`**/auto/` 被 gitignore），
    # 没有它时干净检出无法复跑 --check。
    fixture = FIXTURES / name
    if fixture.is_file():
        return fixture
    return AUTO / name


def parse(path: Path) -> list[tuple[str, str]]:
    pairs: list[tuple[str, str]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        match = PAIR.match(line.strip())
        if match:
            pairs.append((match.group(1), match.group(2)))
    pairs.sort()
    keys = [key for key, _ in pairs]
    if len(set(keys)) != len(keys):
        raise SystemExit(f"duplicate keys in {path.name}")
    return pairs


def render() -> str:
    lines = [
        "// Generated by tools/gen_mime_tables.py from tools/fixtures/*.gperf",
        "// (copies of the gperf sources the build writes into tdutils/generate/auto/).",
        "// Do not edit by hand; re-run the generator instead.",
        "",
    ]
    for name, file_name, key_name, value_name in SOURCES:
        path = source_path(file_name)
        if not path.is_file():
            raise SystemExit(
                f"missing {path} (restore tools/fixtures/{file_name} or build the C++ tree)"
            )
        pairs = parse(path)
        lines.append(f"pub static {name}: [(&str, &str); {len(pairs)}] = [")
        for key, value in pairs:
            lines.append(f'    ("{key}", "{value}"),  // {key_name} -> {value_name}')
        lines.append("];")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    rendered = render()
    if "--check" in argv:
        if not OUT.is_file():
            print(f"FAIL missing {OUT}")
            return 1
        existing = OUT.read_text(encoding="utf-8")
        if existing.replace("\r\n", "\n") != rendered:
            print(f"FAIL {OUT} is stale; re-run without --check")
            return 1
        print("PASS mime tables are byte-identical to the generator output")
        return 0
    OUT.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(rendered.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))