"""Extract TDLib's packed emoji list into a Rust table.

命令:
    python tools/gen_emoji_table.py            # 重新生成 rust/src/emoji_table.rs
    python tools/gen_emoji_table.py --check    # 重新生成并逐字节比对，不一致退出 1

判据:
    解码 `tdutils/td/utils/emoji.cpp` 里那段 base64url+gzip 的 `packed_emojis`，
    按空格切分后必须是 **2370** 项（C++ 侧 `EMOJI_COUNT` 的 CHECK 值），且 `--check` 逐字节相同。

覆盖边界:
    只覆盖 `find_emojis` 用的基础 emoji 表（不含 ZWJ，TDLib 用 `\u200D` 拼接）。
    覆盖不到：`find_emojis` 的运行时算法（在 rust/src/lib.rs 里实现）、非 TD_HAVE_ZLIB 构建（表为空）。

失效条件:
    TDLib 更新了 emoji 数据（packed 串变化、EMOJI_COUNT 变化）或换用别的压缩格式。
"""

from __future__ import annotations

import base64
import gzip
import re
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tdutils" / "td" / "utils" / "emoji.cpp"
OUT = ROOT / "rust" / "src" / "emoji_table.rs"
EXPECTED_COUNT = 2370


def extract_packed() -> str:
    text = SOURCE.read_text(encoding="utf-8")
    start = text.index("packed_emojis(")
    end = text.index(");", start)
    literals = re.findall(r'"([^"]*)"', text[start:end])
    return "".join(literals)


def decode(packed: str) -> list[str]:
    raw = base64.urlsafe_b64decode(packed + "=" * (-len(packed) % 4))
    try:
        data = gzip.decompress(raw).decode("utf-8")
    except gzip.BadGzipFile:
        data = zlib.decompress(raw).decode("utf-8")
    if data.endswith(" "):
        data = data[:-1]
    emojis = data.split(" ")
    return emojis


def render() -> str:
    emojis = decode(extract_packed())
    if len(emojis) != EXPECTED_COUNT:
        raise SystemExit(f"expected {EXPECTED_COUNT} emoji, decoded {len(emojis)}")
    if len(set(emojis)) != len(emojis):
        raise SystemExit("duplicate emoji in decoded table")
    emojis.sort()
    lines = [
        "// Generated by tools/gen_emoji_table.py from tdutils/td/utils/emoji.cpp.",
        "// Do not edit by hand; re-run the generator instead.",
        "",
        f"pub static EMOJIS: [&str; {len(emojis)}] = [",
    ]
    for emoji in emojis:
        lines.append(f'    "{emoji}",')
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    rendered = render()
    if "--check" in argv:
        if not OUT.is_file():
            print(f"FAIL missing {OUT}")
            return 1
        existing = OUT.read_text(encoding="utf-8")
        if existing.replace("\r\n", "\n") != rendered:
            print(f"FAIL {OUT} is stale; re-run without --check")
            return 1
        print("PASS emoji table is byte-identical to the generator output")
        return 0
    OUT.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(rendered.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))