"""Generate rust/src/tl_schema.rs: argument tables for every td_api function and constructor.

命令:
    uv run python tools/gen_tl_schema.py            # 重新生成
    uv run python tools/gen_tl_schema.py --check    # 只校验（逐字节比较）

判据:
    退出码 0 = 生成内容与 rust/src/tl_schema.rs 逐字节相同；非 0 = 漂移。

覆盖边界:
    只有「名字 → 字段名 → TL 类型」的表，没有行为。`td_api.tl` 的 4 条特殊定义
    （`vector {t:Type}`、`double ?`、`string ?`、`int32` 裸可空标记）被跳过，与 F040 一致。
    构造号取自构建产物 `td/generate/auto/td/telegram/td_api.h`（F091）：那是对**规范化**后
    的 TL 声明求的 crc32，与直接对源码行求 crc32 在 422/3464 个定义上不同。

失效条件:
    `td/generate/scheme/td_api.tl`、生成的头文件或 `rust/src/api_functions.rs` 变化——
    重跑本生成器（需要先构建一次，`td/generate/auto/` 是 gitignored 的构建产物）。
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "td" / "generate" / "scheme" / "td_api.tl"
FUNCTIONS = ROOT / "rust" / "src" / "api_functions.rs"
OUT = ROOT / "rust" / "src" / "tl_schema.rs"
HEADER = ROOT / "td" / "generate" / "auto" / "td" / "telegram" / "td_api.h"


def header_ids() -> dict[str, int]:
    if not HEADER.is_file():
        raise SystemExit(f"FAIL {HEADER.relative_to(ROOT)} missing; run a build first (tools/verify.py does)")
    ids: dict[str, int] = {}
    name = None
    for line in HEADER.read_text(encoding="utf-8", errors="replace").splitlines():
        match = re.match(r"class (\w+) final : public", line)
        if match:
            name = match.group(1)
            continue
        match = re.match(r"\s*static const std::int32_t ID = (-?\d+);", line)
        if match and name is not None:
            ids[name] = int(match.group(1))
            name = None
    return ids


def parse_schema() -> dict[str, tuple[list[tuple[str, str]], str]]:
    definitions: dict[str, tuple[list[tuple[str, str]], str]] = {}
    for raw in SCHEMA.read_text(encoding="utf-8").splitlines():
        line = raw.split("//", 1)[0].strip()
        if not line or not line.endswith(";"):
            continue
        body = line[:-1].strip()
        if "{" in body or "[" in body:
            continue
        if "=" not in body:
            continue
        left = body.split("=", 1)[0]
        parts = left.split()
        name = parts[0]
        args: list[tuple[str, str]] = []
        if any(":" not in part for part in parts[1:]):
            # `double ? = Double;` / `string ? = String;`: TL's bare nullable markers (F040)
            continue
        for part in parts[1:]:
            arg_name, arg_type = part.split(":", 1)
            args.append((arg_name, arg_type))
        if name in definitions:
            raise SystemExit(f"FAIL duplicated definition {name}")
        definitions[name] = (args, body)
    return definitions


def parse_functions() -> set[str]:
    names = set(re.findall(r'\(-?\d+, "([^"]+)"\)', FUNCTIONS.read_text(encoding="utf-8")))
    if len(names) != 1114:
        raise SystemExit(f"FAIL expected 1114 functions, found {len(names)}")
    return names


def render(definitions: dict[str, tuple[list[tuple[str, str]], str]], functions: set[str]) -> str:
    missing = sorted(functions - definitions.keys())
    if missing:
        raise SystemExit(f"FAIL functions missing from schema: {missing[:5]}")
    # 3473 definition lines minus the 3 special forms skipped above (vector / double ? / string ?)
    if len(definitions) != 3470:
        raise SystemExit(f"FAIL expected 3470 definitions, found {len(definitions)}")

    arguments: list[str] = []
    constructors: list[str] = []
    constructor_ids: list[str] = []
    ids = header_ids()
    for name in sorted(definitions):
        args, body = definitions[name]
        fields = ", ".join(f'("{field}", "{kind}")' for field, kind in args)
        line = f'    ("{name}", &[{fields}]),'
        (arguments if name in functions else constructors).append(line)
        if name not in functions:
            # int32/int53/int64/bytes/boolFalse/boolTrue are TL builtins: they never appear as an
            # "@type" object, so they have no dispatch id in the generated header and no row here
            if name in ids:
                constructor_ids.append(f'    ({ids[name]}, "{name}"),')

    lines = [
        "// @generated by tools/gen_tl_schema.py from td/generate/scheme/td_api.tl; do not edit.",
        "//",
        f"// {len(arguments)} functions, {len(constructors)} constructors.",
        "// Argument tables only (name -> field -> TL type); behaviour lives in lib.rs.",
        "",
        "pub static ARGUMENTS: &[(&str, &[(&str, &str)])] = &[",
        *arguments,
        "];",
        "",
        "pub static CONSTRUCTORS: &[(&str, &[(&str, &str)])] = &[",
        *constructors,
        "];",
        "",
        "// Constructor ids: crc32 of the definition line without ';', same as api_functions.rs.",
        "pub static CONSTRUCTOR_IDS: &[(i32, &str)] = &[",
        *constructor_ids,
        "];",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    content = render(parse_schema(), parse_functions())
    if args.check:
        if not OUT.is_file():
            print(f"FAIL missing {OUT.relative_to(ROOT)}")
            return 1
        if OUT.read_bytes() != content.encode():
            print(f"FAIL {OUT.relative_to(ROOT)} differs from td_api.tl")
            return 1
        print(f"PASS {OUT.relative_to(ROOT)} matches td_api.tl")
        return 0

    OUT.write_bytes(content.encode())
    print(f"wrote {OUT.relative_to(ROOT)} ({len(content)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())