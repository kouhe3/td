"""Extract tdutils' unicode tables into a Rust module.

命令:
    uv run python tools/gen_unicode_tables.py            # 重新生成 rust/src/unicode_tables.rs
    uv run python tools/gen_unicode_tables.py --check    # 重新生成并逐字节比对，不一致退出 1

判据:
    解析 `tdutils/td/utils/unicode.cpp` 里的字面量（不手抄），逐项断言 C++ 侧的 CHECK 值：
    `TABLE_SIZE` 是 1280；三张 int16 表各 1280 项；`unicode_simple_category_ranges` 1655 项且
    末项是 4294967295 哨兵；三张 int32 范围表分别是 3126 / 384 / 6980 项，都以
    (2147483647, 0) 收尾，`binary_search_ranges` 要求偶数项且区间起点严格递增。
    `--check` 必须逐字节相同。

覆盖边界:
    只覆盖 `unicode.h` 四个函数背后的静态表；`get_unicode_simple_category` 的跳表
    (`unicode_simple_category_jump_pos`) 与 ASCII 串表不导出——Rust 侧用范围表统一处理，
    等价性由 tools/unicode_diff.py 的 0..=0x10FFFF 全扫判定。
    覆盖不到的：表在运行时的语义（在 rust/src/lib.rs 里实现）。

失效条件:
    TDLib 更新了 unicode.cpp 的表（项数、哨兵、起点变化）——生成器的断言先红；
    或改了数组的 C++ 类型（int16/int32/u32 宽度不同）。
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tdutils" / "td" / "utils" / "unicode.cpp"
OUT = ROOT / "rust" / "src" / "unicode_tables.rs"

HEADER = """// Generated by tools/gen_unicode_tables.py from tdutils/td/utils/unicode.cpp.
// Do not edit by hand; re-run the generator instead.
"""

# (C++ name, Rust name, Rust type, expected length, expected last element)
NUMERIC_TABLES = [
    ("unicode_simple_category_ranges", "UNICODE_SIMPLE_CATEGORY_RANGES", "u32", 1655, 0xFFFF_FFFF),
    ("prepare_search_character_table", "PREPARE_SEARCH_CHARACTER_TABLE", "i16", 1280, None),
    ("prepare_search_character_ranges", "PREPARE_SEARCH_CHARACTER_RANGES", "i32", 3126, (2147483647, 0)),
    ("to_lower_table", "TO_LOWER_TABLE", "i16", 1280, None),
    ("to_lower_ranges", "TO_LOWER_RANGES", "i32", 384, (2147483647, 0)),
    ("without_diacritics_table", "WITHOUT_DIACRITICS_TABLE", "i16", 1280, None),
    ("without_diacritics_ranges", "WITHOUT_DIACRITICS_RANGES", "i32", 6980, (2147483647, 0)),
]
BOUNDS = {"u32": (0, 0xFFFF_FFFF), "i16": (-32768, 32767), "i32": (-2147483648, 2147483647)}
ITEM = re.compile(r"-?(?:0[xX][0-9a-fA-F]+|[0-9]+)")
COMMENT = re.compile(r"//[^\n]*")


def strip_comments(text: str) -> str:
    return COMMENT.sub("", text)


def array_body(text: str, name: str) -> str:
    pattern = re.compile(r"\b" + re.escape(name) + r"\s*(?:\[[^\]]*\])?\s*=\s*\{([^}]*)\}")
    matches = pattern.findall(text)
    if len(matches) != 1:
        raise SystemExit(f"expected exactly one definition of {name}, found {len(matches)}")
    return matches[0]


def parse_items(body: str, name: str) -> list[int]:
    values: list[int] = []
    for token in body.split(","):
        token = token.strip()
        if not token:
            continue
        if ITEM.fullmatch(token) is None:
            raise SystemExit(f"{name}: cannot parse item {token!r}")
        values.append(int(token, 0))
    return values


def parse_table_size(text: str) -> int:
    match = re.search(r"\bTABLE_SIZE\s*=\s*([0-9]+)\s*;", text)
    if match is None:
        raise SystemExit("cannot parse TABLE_SIZE")
    return int(match.group(1))


def check(values: list[int], name: str, rust_type: str, length: int, last: object) -> None:
    if len(values) != length:
        raise SystemExit(f"{name}: expected {length} items, parsed {len(values)}")
    low, high = BOUNDS[rust_type]
    for value in values:
        if not low <= value <= high:
            raise SystemExit(f"{name}: {value} does not fit {rust_type}")
    if last is None:
        return
    expected = list(last) if isinstance(last, tuple) else [last]
    if values[-len(expected) :] != expected:
        raise SystemExit(f"{name}: tail is {values[-len(expected) :]!r}, expected {expected!r}")
    if isinstance(last, tuple):
        if len(values) % 2 != 0:
            raise SystemExit(f"{name}: {len(values)} items is not a whole number of pairs")
        begins = values[0::2]
        if any(before >= after for before, after in zip(begins, begins[1:])):
            raise SystemExit(f"{name}: range begins are not strictly increasing")


def render_array(name: str, rust_type: str, values: list[int]) -> str:
    lines = [f"pub const {name}: [{rust_type}; {len(values)}] = ["]
    for index in range(0, len(values), 16):
        lines.append("    " + ",".join(str(value) for value in values[index : index + 16]) + ",")
    lines.append("];")
    return "\n".join(lines) + "\n"


def render() -> str:
    text = strip_comments(SOURCE.read_text(encoding="utf-8"))
    table_size = parse_table_size(text)
    if table_size != 1280:
        raise SystemExit(f"TABLE_SIZE is {table_size}, expected 1280")
    parts = [HEADER, f"pub const TABLE_SIZE: u32 = {table_size};\n"]
    for cpp_name, rust_name, rust_type, length, last in NUMERIC_TABLES:
        values = parse_items(array_body(text, cpp_name), cpp_name)
        check(values, cpp_name, rust_type, length, last)
        parts.append(render_array(rust_name, rust_type, values))
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    text = render()
    if args.check:
        current = OUT.read_bytes() if OUT.exists() else b""
        if current != text.encode():
            print(f"OUT OF DATE: {OUT.relative_to(ROOT)} differs from a fresh generation")
            return 1
        print(f"PASS {OUT.relative_to(ROOT)} is up to date")
        return 0

    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())