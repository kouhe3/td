"""Decode TDLib's embedded `en` country list into the Rust table.

命令:
    python tools/gen_country_table.py            # 重写 rust/src/country_table.rs
    python tools/gen_country_table.py --check    # 与已提交的表逐字节比对

判据:
    源是 `td/telegram/CountryInfoManager.cpp` 里那段 gzip+base64（`help.countriesList`，
    constructor 0x87d0759e，hash -882011426）；解出 **235** 个国家，`--check` 逐字节相同。

覆盖边界:
    只有内置的 `en` 快照（其它语言由服务器下发）。`prefixes` 为空时按 C++ 行为补一个空串，
    即该 calling code 匹配任意号码。

失效条件:
    TDLib 更新内置快照（blob 或 hash 变化），或 `help.country` / `help.countryCode` 的构造变了。
"""

from __future__ import annotations

import base64
import gzip
import re
import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "td" / "telegram" / "CountryInfoManager.cpp"
OUT = ROOT / "rust" / "src" / "country_table.rs"
EXPECTED_COUNTRIES = 235
EXPECTED_HASH = -882011426


def extract_blob() -> str:
    text = SOURCE.read_text(encoding="utf-8")
    marker = text.index('static const BufferSlice en = gzdecode(')
    region = text[marker : text.index("));", marker)]
    literals = re.findall(r'"([^"]*)"', region)
    return "".join(literals)


class Reader:
    def __init__(self, data: bytes) -> None:
        self.data = data
        self.pos = 0

    def u32(self) -> int:
        value = struct.unpack_from("<I", self.data, self.pos)[0]
        self.pos += 4
        return value

    def i32(self) -> int:
        return struct.unpack("<i", struct.pack("<I", self.u32()))[0]

    def string(self) -> str:
        first = self.data[self.pos]
        if first < 254:
            length = first
            header = 1
        else:
            length = int.from_bytes(self.data[self.pos + 1 : self.pos + 4], "little")
            header = 4
        self.pos += header
        value = self.data[self.pos : self.pos + length].decode("utf-8")
        self.pos += length
        self.pos += -(header + length) % 4
        return value

    def vector_len(self) -> int:
        constructor = self.u32()
        if constructor != 0x1CB5C415:
            raise SystemExit(f"expected vector constructor, got 0x{constructor:08x}")
        return self.u32()


def parse_countries() -> tuple[list[dict], int]:
    raw = base64.urlsafe_b64decode(extract_blob() + "=" * (-len(extract_blob()) % 4))
    try:
        payload = gzip.decompress(raw)
    except gzip.BadGzipFile:
        payload = zlib.decompress(raw)
    reader = Reader(payload)
    constructor = reader.u32()
    if constructor != 0x87D0759E:
        raise SystemExit(f"unexpected countriesList constructor 0x{constructor:08x}")
    count = reader.vector_len()
    countries = []
    for _ in range(count):
        country_constructor = reader.u32()
        if country_constructor != 0xC3878E23:
            raise SystemExit(f"unexpected country constructor 0x{country_constructor:08x}")
        flags = reader.u32()
        is_hidden = bool(flags & 1)
        if flags & 2:
            reader.string()  # localized name; the embedded snapshot carries none
        iso2 = reader.string()
        default_name = reader.string()
        codes = []
        code_count = reader.vector_len()
        for _ in range(code_count):
            code_constructor = reader.u32()
            if code_constructor != 0x4203C5EF:
                raise SystemExit(f"unexpected countryCode constructor 0x{code_constructor:08x}")
            code_flags = reader.u32()
            calling_code = reader.string()
            prefixes: list[str] = []
            if code_flags & 1:
                prefix_count = reader.vector_len()
                prefixes = [reader.string() for _ in range(prefix_count)]
            patterns: list[str] = []
            if code_flags & 2:
                pattern_count = reader.vector_len()
                patterns = [reader.string() for _ in range(pattern_count)]
            if not prefixes:
                prefixes = [""]
            codes.append({"calling_code": calling_code, "prefixes": prefixes, "patterns": patterns})
        countries.append(
            {
                "country_code": iso2,
                "default_name": default_name,
                "is_hidden": is_hidden,
                "calling_codes": codes,
            }
        )
    hash_value = reader.i32()
    if reader.pos != len(payload):
        raise SystemExit(f"trailing bytes: pos={reader.pos} len={len(payload)}")
    return countries, hash_value


def render() -> str:
    countries, hash_value = parse_countries()
    if len(countries) != EXPECTED_COUNTRIES:
        raise SystemExit(f"expected {EXPECTED_COUNTRIES} countries, decoded {len(countries)}")
    if hash_value != EXPECTED_HASH:
        raise SystemExit(f"expected hash {EXPECTED_HASH}, decoded {hash_value}")
    lines = [
        "// Country table for getPhoneNumberInfoSync, generated by tools/gen_country_table.py from",
        f"// the `en` `help.countriesList` snapshot (gzip+base64, constructor 0x87d0759e, hash {hash_value})",
        "// embedded in td/telegram/CountryInfoManager.cpp. Do not edit by hand.",
        "//",
        "// Order matters: get_phone_number_info_object keeps the first country/calling code that",
        "// reaches the longest `calling_code + prefix` match, and the first of two patterns with the",
        "// same number of matched digits. `prefixes` is never empty here because the C++ side resizes",
        "// an absent prefix list to one empty string, which makes that calling code match every number.",
        "// The snapshot contains no localized `name` values (0 of 235), so countryInfo.name always",
        "// falls back to default_name.",
        "",
        "pub struct CallingCode {",
        "    pub calling_code: &'static str,",
        "    pub prefixes: &'static [&'static str],",
        "    pub patterns: &'static [&'static str],",
        "}",
        "",
        "pub struct Country {",
        "    pub country_code: &'static str,",
        "    pub default_name: &'static str,",
        "    pub is_hidden: bool,",
        "    pub calling_codes: &'static [CallingCode],",
        "}",
        "",
        f"pub static COUNTRIES: [Country; {len(countries)}] = [",
    ]
    for country in countries:
        lines.append("    Country {")
        lines.append(f'        country_code: "{country["country_code"]}",')
        lines.append(f'        default_name: "{country["default_name"]}",')
        lines.append(f'        is_hidden: {str(country["is_hidden"]).lower()},')
        lines.append("        calling_codes: &[")
        for code in country["calling_codes"]:
            prefixes = ", ".join(f'"{value}"' for value in code["prefixes"])
            patterns = ", ".join(f'"{value}"' for value in code["patterns"])
            lines.append(
                f'            CallingCode {{ calling_code: "{code["calling_code"]}", '
                f"prefixes: &[{prefixes}], patterns: &[{patterns}] }},"
            )
        lines.append("        ],")
        lines.append("    },")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    rendered = render()
    if "--check" in argv:
        if not OUT.is_file():
            print(f"FAIL missing {OUT}")
            return 1
        existing = OUT.read_text(encoding="utf-8")
        if existing.replace("\r\n", "\n") != rendered:
            print(f"FAIL {OUT} is stale; re-run without --check")
            return 1
        print("PASS country table is byte-identical to the generator output")
        return 0
    OUT.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(rendered.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))